// Returns the ISO 4217 currency code for a given country name, or '' if unknown
export function currencyForCountry(name) {
  const country = COUNTRIES.find((c) => c.name === name)
  return country ? (COUNTRY_CURRENCIES[country.code] ?? '') : ''
}

// Convert ISO 3166-1 alpha-2 code to flag emoji
export function flagEmoji(code) {
  if (!code || code.length !== 2) return '🌐'
  return [...code.toUpperCase()]
    .map((c) => String.fromCodePoint(c.charCodeAt(0) + 127397))
    .join('')
}

// Lookup a country by name (case-insensitive)
export function countryByName(name) {
  const n = (name ?? '').toLowerCase()
  return COUNTRIES.find((c) => c.name.toLowerCase() === n) ?? null
}
